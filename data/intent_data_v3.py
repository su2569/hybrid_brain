def build_v3(output_path):
    samples = []
    for text in NORMAL:
        samples.append({"text": text, "intent": "normal"})
    for text in INDUCE:
        samples.append({"text": text, "intent": "induce"})
    for text in MALICIOUS:
        samples.append({"text": text, "intent": "malicious"})
    for text in VAGUE:
        samples.append({"text": text, "intent": "vague"})

    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump({"samples": samples}, f, ensure_ascii=False, indent=2)

    from collections import Counter
    cnt = Counter(s["intent"] for s in samples)
    print(f"[intent v3] {len(samples)} 条 → {output_path}")
    for k, v in cnt.items():
        print(f"  {k}: {v}")
    return samples



def build(output_path):
    samples = []
    for t in QUERY:
        samples.append({"text": t, "intent": "query"})
    for t in CHAT:
        samples.append({"text": t, "intent": "chat"})
    for t in ABUSE:
        samples.append({"text": t, "intent": "abuse"})
    for t in MANIPULATE:
        samples.append({"text": t, "intent": "manipulate"})

    random.shuffle(samples)
    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump({"samples": samples}, f, ensure_ascii=False, indent=2)

    from collections import Counter
    cnt = Counter(s["intent"] for s in samples)
    print(f"[intent v4] {len(samples)} 条 → {output_path}")
    for k, v in cnt.items():
        print(f"  {k}: {v}")
    return samples



def build(output_path):
    samples = []
    for cur, nxt in CONTINUE:
        samples.append({"input": cur, "next": nxt, "label": "continue"})
    for cur, nxt in SWITCH:
        samples.append({"input": cur, "next": nxt, "label": "switch"})
    for cur, nxt in CORRECT:
        samples.append({"input": cur, "next": nxt, "label": "correct"})
    for cur, nxt in END:
        samples.append({"input": cur, "next": nxt, "label": "end"})

    import random
    random.shuffle(samples)

    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump({"samples": samples}, f, ensure_ascii=False, indent=2)

    from collections import Counter
    cnt = Counter(s["label"] for s in samples)
    print(f"[behavior v2] {len(samples)} 条 → {output_path}")
    for k, v in cnt.items():
        print(f"  {k}: {v}")
    return samples



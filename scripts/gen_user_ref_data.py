data = []
for t in STATEMENT: data.append({"text": t, "label": "statement"})
for t in QUERY: data.append({"text": t, "label": "query"})
for t in IRRELEVANT: data.append({"text": t, "label": "irrelevant"})
for t, l in BOUNDARY: data.append({"text": t, "label": l})

random.seed(42)
random.shuffle(data)
n_val = max(20, len(data) // 5)
val, train = data[:n_val], data[n_val:]

def write(p, items):
    with open(p, "w", encoding="utf-8") as f:
        for x in items:
            f.write(json.dumps(x, ensure_ascii=False) + "\n")
    print(f"  {p}: {len(items)}")

write("data/classifiers/user_ref_train.jsonl", train)
write("data/classifiers/user_ref_val.jsonl", val)

